import assert from 'node:assert/strict'
import { existsSync, readFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = process.cwd()
const required = [
  'AGENTS.md',
  'README.md',
  'docs/architecture/frontend-architecture.md',
  'docs/workflows/CODE_REVIEW.md',
  '.github/workflows/quality.yml',
  '.github/workflows/package.yml',
  '.github/rulesets/main.json',
  '.github/pull_request_template.md',
  'src/app/main.tsx',
  'src/app/App.test.tsx',
]

for (const path of required) {
  assert(existsSync(resolve(root, path)), `Missing baseline file: ${path}`)
}

const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'))
const scripts = ['dev', 'build', 'lint', 'format:check', 'typecheck', 'test:ci', 'quality']
for (const name of scripts) {
  assert(typeof pkg.scripts?.[name] === 'string', `Missing npm script: ${name}`)
}

const workflow = readFileSync(resolve(root, '.github/workflows/quality.yml'), 'utf8')
assert(workflow.includes('name: Frontend Quality'), 'Required CI check name changed')
assert(workflow.includes('pull_request:'), 'PR checks are not configured')
assert(workflow.includes('npm ci'), 'CI must install from a committed lockfile')

const ruleset = JSON.parse(readFileSync(resolve(root, '.github/rulesets/main.json'), 'utf8'))
const checks = ruleset.rules.find((rule) => rule.type === 'required_status_checks')
assert(
  checks?.parameters?.required_status_checks?.some((rule) => rule.context === 'Frontend Quality'),
  'Ruleset must require the real Frontend Quality CI context',
)

const review = readFileSync(resolve(root, 'AGENTS.md'), 'utf8')
assert(review.includes('## Code Review Rules'), 'Codex review rules are missing')

if (process.env.GITHUB_ACTIONS) {
  assert(existsSync(resolve(root, 'package-lock.json')), 'CI requires package-lock.json')
} else if (!existsSync(resolve(root, 'package-lock.json'))) {
  console.warn('package-lock.json will be generated by npm install during bootstrap.')
}

console.log(`Repository baseline verified (${required.length} required files).`)
